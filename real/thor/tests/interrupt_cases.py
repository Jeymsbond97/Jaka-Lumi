"""People talking to Lumi while it is on a mission (docs/17), and what it must do with each thing they say.

SCENARIOS = [{"mission", "recipient", "sender", "state", "turns"}]
- mission: the command that started it; recipient / sender: names as written in it, or None.
- turns: [{"say", "who", "expect", "reply_must", "reply_must_not", "new_steps"}], in order, one person after another.
  who: stranger | recipient | sender | owner (owner = whoever typed or said the mission command).
  expect: halt_talk (halt, turn to them, greet / ask how to help), answer (answer, then ask "may I go on?"),
  refuse_redirect (keep the mission, say for whom it is, offer help after), give_here (hand it over now, mission done),
  change_task (new_steps replace the rest), cancel (mission ends), safety_stop (halt until told to go on),
  resume (goodbye / thanks, go on with the mission), ask_language (ask for English or Korean).
  say "": nobody answered for a few seconds after Lumi asked whether it may go on.
- reply_must / reply_must_not: case-insensitive pieces of the spoken reply, in the reply's language.
- new_steps: change_task only, the short notation of tests/test_steps.py plus `give <Name>`.
Speech is written as the recogniser returns it: missing punctuation, fillers, lower case.
"""


def T(say, who, expect, must=(), must_not=(), steps=None):
    t = {"say": say, "who": who, "expect": expect, "reply_must": list(must), "reply_must_not": list(must_not)}
    if steps is not None:
        t["new_steps"] = steps
    return t


def S(mission, recipient, sender, state, *turns):
    return {"mission": mission, "recipient": recipient, "sender": sender, "state": state, "turns": list(turns)}


