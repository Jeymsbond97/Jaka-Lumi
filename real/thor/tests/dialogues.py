"""Multi-turn conversations with Lumi: what visitors say, turn by turn, and what each reply must (not) contain.

DIALOGUES = [{"who": persona, "topic", "lang": main language, "turns": [turn, ...]}]
turn = {"say", "expect_action", "must", "must_not", "check", "reply_lang"}
- expect_action: what Lumi must do, alternatives split by " | ": none (only talk), weather, search, unclear,
  status, mission, end, go_to p3, come, look left, wave, sing, quiet, pick cup, fetch, ... (see brain.ACTION_NAMES).
- must / must_not: case-insensitive regexes on the spoken reply (every must matches, no must_not does).
  {wd} {wdk} {d} {mon} {h12} {h24} {y} are filled with the time of the run (tests/conversation_check.fill).
- check: one line on what a right answer does (handed to the judge in tests/dialogue_check.py).
- reply_lang: the language the reply must be in when it is not the language spoken ("and in Korean?").
Only facts in knowledge/lumi_about_en.md and the docs are required in "must"; for anything Lumi cannot know
(the conference, prices, people) the reply must say it is not sure, or the turn expects a lookup.
"""


def T(say, act="none", must=(), no=(), check=None, rl=None):
    t = {"say": say, "expect_action": act, "must": list(must), "must_not": list(no)}
    if check:
        t["check"] = check
    if rl:
        t["reply_lang"] = rl
    return t


def D(who, topic, lang, *turns):
    return {"who": who, "topic": topic, "lang": lang, "turns": list(turns)}


