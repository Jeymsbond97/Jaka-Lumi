def _grow(kind, parts, n, seed=3):
    """n wordings of the product of `parts` (lists of strings joined as they are), the same sample every run."""
    combos = [" ".join("".join(c).split()) for c in _it.product(*parts)]
    combos = list(dict.fromkeys(combos))
    _random.Random(f"{kind}{seed}").shuffle(combos)
    return combos[:n]


