def _v(cores, tails=("", " 줘", " 봐")):
    """Each plain core with the request tails people add, and written without spaces (a frequent slip)."""
    out = []
    for c in cores:
        for t in tails:
            out.append(c + t)
        if " " in c:
            out.append(c.replace(" ", ""))
    return list(dict.fromkeys(out))


